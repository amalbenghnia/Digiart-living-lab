"""Domain models for the Course Recommendation & Agenda Engine.

These models are completely independent from the Lead model.
They represent:
  - CourseModel:           A course in the catalog (Courses tab)
  - SessionModel:          A scheduled session in the agenda (Agenda tab)
  - MarketTrendModel:      Market scoring data (Market_Trends tab)
  - RecommendationResult:  Output of the deterministic recommendation algorithm
  - RosterEntry:           Calculated view: Agenda + Leads → enrollment state

Design principles:
  - No LLM calls in any of these models (pure data structures)
  - Course ID is the universal key linking all tabs (not course title)
  - Roster is always a calculated view, never a stored table
"""
from __future__ import annotations

from pydantic import BaseModel, Field


class CourseModel(BaseModel):
    """A course in the master catalog."""
    course_id: str
    title: str
    category: str
    level: str               # Beginner / Intermediate / Advanced
    capacity: int = 20
    status: str = "active"   # active / inactive / archived


class SessionModel(BaseModel):
    """A scheduled session (one occurrence of a course on a given date)."""
    session_id: str
    course_id: str
    title: str
    date: str                # YYYY-MM-DD
    start_time: str = "09:00"
    end_time: str = "17:00"
    capacity: int = 20
    format: str = "On-site"  # On-site / Online / Hybrid
    status: str = "open"     # open / full / cancelled / completed


class MarketTrendModel(BaseModel):
    """Market intelligence scores for a course (0–100 each)."""
    course_id: str
    title: str
    market_demand: float = Field(ge=0, le=100)     # 40% weight
    industry_trend: float = Field(ge=0, le=100)    # 30% weight
    business_priority: float = Field(ge=0, le=100) # 10% weight
    notes: str = ""
    confidence: float = 0.0
    evidence_count: int = 0
    last_updated: str = ""


class RecommendationResult(BaseModel):
    """Output of the deterministic recommendation algorithm for one course.

    Final Score = 0.40 × market_demand
               + 0.30 × industry_trend
               + 0.20 × historical_demand   ← computed from Leads (COUNT by course_id)
               + 0.10 × business_priority

    Priority thresholds:
      score >= 90 → P0
      score >= 75 → P1
      score <  75 → P2
    """
    rank: int
    course_id: str
    title: str
    category: str
    final_score: float
    market_demand: float
    industry_trend: float
    historical_demand: float     # Derived from real lead data (0-100)
    historical_lead_count: int   # Raw number of leads matching this course
    business_priority: float
    priority: str                # P0 / P1 / P2
    confidence: float = 0.0      # Added for MI Agent v2
    reason: str                  # Human-readable explanation (generated by LLM optionally)



class RosterEntry(BaseModel):
    """Calculated enrollment state for one session.

    This is NEVER stored — it is always computed on-the-fly from:
      - Agenda tab (capacity)
      - Leads tab (COUNT where status in [confirmed_unpaid, paid] and course matches)
    """
    session_id: str
    course_id: str
    title: str
    date: str
    format: str
    capacity: int
    registered: int              # confirmed_unpaid + paid leads for this course
    available: int               # capacity - registered
    fill_rate: float             # registered / capacity * 100
    fill_status: str             # "Open" / "Almost Full" / "Full"

    @classmethod
    def compute_fill_status(cls, registered: int, capacity: int) -> str:
        if capacity == 0:
            return "Full"
        available = capacity - registered
        if available <= 0:
            return "Full"
        if available <= 3:
            return "Almost Full"
        return "Open"
