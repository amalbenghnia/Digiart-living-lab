"""RecommendationService — deterministic course ranking engine.

DESIGN PRINCIPLE: No LLM in this file. The score is 100% deterministic
and explainable. An encadrant or manager can verify every result
with a simple calculator.

Scoring formula (weights must sum to 1.0):
  Final Score = 0.40 × Market Demand      (from Market_Trends tab, set by MI Agent)
              + 0.40 × Industry Trend      (from Market_Trends tab, set by MI Agent)
              + 0.10 × Historical Demand   (calculated from real Leads data)
              + 0.10 × Business Priority   (from Market_Trends tab, manual)

Priority thresholds:
  Final Score >= 80  →  P0  (launch immediately)
  Final Score >= 65  →  P1  (high priority, plan soon)
  Final Score <  65  →  P2  (watch and assess)

Historical Demand calculation:
  - Count leads per course_id (future-proof: uses course_id when available,
    falls back to fuzzy title match for backward compatibility with existing
    leads that store training as free text)
  - Normalized to 0–100 scale: (count / total_leads) × 500, capped at 100
  - If no leads exist for a course → historical_demand = 0

The Market Intelligence Agent populates Market_Trends via POST /market/refresh.
Scores are updated in Google Sheets and cached for 60 seconds.
"""
from __future__ import annotations

from typing import List, Optional

from app.core.logging import get_logger, log_event
from app.models.course import CourseModel, MarketTrendModel, RecommendationResult
from app.repositories.agenda_repository import AgendaRepository

logger = get_logger(__name__)

# Priority thresholds (adjusted for evidence-based realistic data distribution)
_P0_THRESHOLD = 80.0
_P1_THRESHOLD = 65.0

# Scoring weights (must sum to 1.0)
_W_MARKET_DEMAND    = 0.40
_W_INDUSTRY_TREND   = 0.40
_W_HISTORICAL       = 0.10
_W_BUSINESS_PRIORITY = 0.10


def _priority_from_score(score: float) -> str:
    if score >= _P0_THRESHOLD:
        return "P0"
    if score >= _P1_THRESHOLD:
        return "P1"
    return "P2"


def _rank_emoji(rank: int) -> str:
    return {1: "🥇", 2: "🥈", 3: "🥉"}.get(rank, f"#{rank}")


class RecommendationService:
    """Ranks all active courses using a deterministic weighted score."""

    def __init__(self, agenda_repo: AgendaRepository, llm_provider=None):
        self._agenda_repo = agenda_repo
        self._llm = llm_provider  # Optional — only used for reason text

    # ── Historical Demand ────────────────────────────────────────────────────

    @staticmethod
    def _compute_historical_demand(
        course_id: str,
        course_title: str,
        all_leads: list,
    ) -> tuple[float, int]:
        """Count leads interested in this course, normalized 0–100.
        Returns (score_0_to_100, raw_count).
        """
        total = len(all_leads)
        if total == 0:
            return 0.0, 0

        count = 0
        title_lower = course_title.lower()
        for lead in all_leads:
            lead_course_id = getattr(lead, "course_id", None)
            if lead_course_id and lead_course_id == course_id:
                count += 1
            elif lead.training and title_lower in lead.training.lower():
                count += 1

        normalized = min((count / total) * 500, 100.0)
        return round(normalized, 1), count


    # ── Core scoring ─────────────────────────────────────────────────────────

    @staticmethod
    def _compute_score(
        market_demand: float,
        industry_trend: float,
        historical_demand: float,
        business_priority: float,
    ) -> float:
        score = (
            _W_MARKET_DEMAND     * market_demand
            + _W_INDUSTRY_TREND  * industry_trend
            + _W_HISTORICAL      * historical_demand
            + _W_BUSINESS_PRIORITY * business_priority
        )
        return round(min(score, 100.0), 1)

    def _build_reason(
        self,
        course: CourseModel,
        trend: MarketTrendModel,
        score: float,
        priority: str,
        historical_demand: float,
    ) -> str:
        """Generate a plain-text reason. Uses the notes generated by Market Intelligence if available."""
        if trend.notes and len(trend.notes.strip()) > 5:
            return trend.notes
            
        template = (
            f"Score {score:.1f}/100 ({priority}) - "
            f"Market demand {trend.market_demand:.0f}/100, "
            f"Industry trend {trend.industry_trend:.0f}/100, "
            f"Historical demand {historical_demand:.1f}/100, "
            f"Business priority {trend.business_priority:.0f}/100."
        )
        return template

    # ── Public interface ──────────────────────────────────────────────────────

    def get_recommendations(self, all_leads: list) -> List[RecommendationResult]:
        """Main entry point. Returns a ranked list of courses.

        Args:
            all_leads: All Lead objects from the lead repository.
                       Used to compute historical demand per course.

        Returns:
            List of RecommendationResult, sorted by final_score descending.
        """
        courses = self._agenda_repo.get_all_courses()
        trends = self._agenda_repo.get_market_trends()

        # Index trends by course_id for O(1) lookup
        trend_map: dict[str, MarketTrendModel] = {t.course_id: t for t in trends}

        results: list[RecommendationResult] = []

        for course in courses:
            if course.status != "active":
                continue

            trend = trend_map.get(course.course_id)
            if trend is None:
                # No market data → use neutral defaults, still include course
                trend = MarketTrendModel(
                    course_id=course.course_id,
                    title=course.title,
                    market_demand=50.0,
                    industry_trend=50.0,
                    business_priority=50.0,
                )

            historical_score, historical_count = self._compute_historical_demand(
                course.course_id, course.title, all_leads
            )
            score = self._compute_score(
                trend.market_demand,
                trend.industry_trend,
                historical_score,
                trend.business_priority,
            )
            priority = _priority_from_score(score)
            reason = self._build_reason(course, trend, score, priority, historical_score)

            results.append(RecommendationResult(
                rank=0,  # assigned after sort
                course_id=course.course_id,
                title=course.title,
                category=course.category,
                final_score=score,
                market_demand=trend.market_demand,
                industry_trend=trend.industry_trend,
                historical_demand=historical_score,
                historical_lead_count=historical_count,
                business_priority=trend.business_priority,
                priority=priority,
                confidence=trend.confidence,
                reason=reason,
            ))

        # Sort descending by score, assign ranks
        results.sort(key=lambda r: r.final_score, reverse=True)
        for i, r in enumerate(results, start=1):
            r.rank = i

        log_event(
            logger, "api_call", "Recommendations computed",
            total=len(results),
            p0=sum(1 for r in results if r.priority == "P0"),
            p1=sum(1 for r in results if r.priority == "P1"),
        )
        return results

    def get_top_n(self, all_leads: list, n: int = 5) -> List[RecommendationResult]:
        return self.get_recommendations(all_leads)[:n]
